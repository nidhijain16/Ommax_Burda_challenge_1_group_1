"""
Wedge Validity Score (optional pipeline step, default OFF; requires the wedge step).

Wedges are generated by DeepSeek (src/wedges.py). Here a second, independent model
(Kimi K3.1 Pro via the Tesseracted Labs gateway) judges each VALID wedge against a
fixed 5-criterion rubric. Python computes the score; Kimi's own overall number is ignored.

What this score IS: a model-assessed plausibility score (basis "llm_assessed"),
plus a few deterministic data checks done in Python.
What it is NOT: a data-validated or market-sized result. It never changes the card's
status, score or ranking; wedges stay hypotheses with size_status "unvalidated".

Configuration (environment variables): FACTS_GATEWAY_API_KEY, FACTS_GATEWAY_BASE_URL
(same as the wedge step) and FACTS_SCORE_MODEL (default: DEFAULT_SCORE_MODEL).
"""

import json
import math
import os
import re
import time
from typing import Any, Callable, Dict, List, Optional

from . import wedges as W

DEFAULT_SCORE_MODEL = "tesseracted-labs-gmbh/moonshotai/Kimi-K3.1-Pro"

WEIGHTS = {
    "evidence_support": 0.30,
    "entity_grounding": 0.25,
    "specificity": 0.15,
    "decision_clarity": 0.15,
    "distinctiveness": 0.15,
}
CRITERIA = tuple(WEIGHTS)
MAX_UNKNOWN = 1          # 2 or more unknown/invalid criteria -> unscored
SIBLING_OVERLAP = 0.6
RECORD_TEXT_CHARS = 1500  # per cited record, in the prompt only

SYSTEM_PROMPT = (
    "You are an independent reviewer of proposed narrower TOP-list wedges for Hubert Burda Media / FACTS. "
    "Judge ONE wedge against the card's fact atoms and the text of the cited records. "
    "Score each criterion with an integer 0-4, or null if you cannot judge it:\n"
    "- evidence_support: do the cited records actually support the wedge's claim?\n"
    "- entity_grounding: is the named entity group visible in the cited records (not invented)?\n"
    "- specificity: one entity type + one decision moment, narrower than the parent title?\n"
    "- decision_clarity: is it a real, consequential consumer decision moment?\n"
    "- distinctiveness: not a near-duplicate of the parent title or of the sibling wedges?\n"
    "Each criterion needs a one-sentence reason. Reasons may cite ONLY record IDs from the wedge's "
    "evidence_ids or the card's fact atoms. Do not invent record IDs or numbers.\n"
    "Return STRICT JSON only, exactly this shape:\n"
    '{"criteria": {"evidence_support": {"score": 0-4 or null, "reason": string or null}, '
    '"entity_grounding": {...}, "specificity": {...}, "decision_clarity": {...}, "distinctiveness": {...}}}'
)


# --------------------------------------------------------------------------- helpers

def model_label(model: str) -> str:
    return W.model_label(model)


def _record_text(rec: Dict[str, Any]) -> str:
    return "\n".join("%s: %s" % (k, v) for k, v in rec.items() if not str(k).startswith("_"))


def _extract_json_object(text: Optional[str]) -> Optional[dict]:
    if not text:
        return None
    t = re.sub(r"```(?:json)?", "", text).strip()
    start, end = t.find("{"), t.rfind("}")
    if start == -1 or end <= start:
        return None
    try:
        out = json.loads(t[start:end + 1])
    except (ValueError, TypeError):
        return None
    return out if isinstance(out, dict) else None


def _space_ids(card: Dict[str, Any], loader) -> set:
    dossier = loader.get_topic_dossier(card.get("topic_key", "")) or {}
    return {s.get("context_id") or s.get("space_id") for s in dossier.get("spaces", [])} - {None, ""}


def build_messages(card: Any, wedge: Dict[str, Any], siblings: List[Dict[str, Any]], loader,
                   index: Optional[int] = None) -> List[Dict[str, str]]:
    c = W._card_dict(card)
    registry = getattr(loader, "by_id", {}) or {}
    cited = {}
    for eid in wedge.get("evidence_ids") or []:
        if eid in registry:
            cited[eid] = _record_text(registry[eid])[:RECORD_TEXT_CHARS]
    payload = {
        # parent title and sibling titles are needed to judge specificity / distinctiveness
        "parent_title": c.get("proposed_topic", ""),
        "fact_atoms": W.fact_atoms(c),
        "wedge": {k: wedge.get(k) for k in
                  ("title", "entity_type", "decision_moment", "region", "rationale", "evidence_ids")},
        "sibling_wedge_titles": [s.get("title", "") for i, s in enumerate(siblings)
                                 if i != index and s is not wedge],
        "cited_records": cited,
    }
    user = "Review input:\n" + json.dumps(payload, ensure_ascii=False, indent=2) + "\n\nReturn the STRICT JSON object."
    return [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": user}]


# --------------------------------------------------------------------------- deterministic parts

def data_checks(card: Any, wedge: Dict[str, Any], siblings: List[Dict[str, Any]], loader,
                index: Optional[int] = None) -> Dict[str, Any]:
    """Python-only checks shown next to the score. They never change the score.

    `index` is the wedge's position in `siblings` (if omitted, it is found by identity).
    """
    if index is None:
        index = next((i for i, s in enumerate(siblings) if s is wedge), None)
    c = W._card_dict(card)
    registry = getattr(loader, "by_id", {}) or {}
    ids = [e for e in (wedge.get("evidence_ids") or []) if isinstance(e, str)]
    card_ids = set(c.get("evidence") or [])
    texts = [_record_text(registry[e]).lower() for e in ids if e in registry]

    # main content words of entity_type: at least half of them (min 1) in ONE cited record (substring match)
    words = [w for w in W._content_tokens(wedge.get("entity_type", "")) if len(w) >= 3]
    need = max(1, math.ceil(len(words) / 2.0)) if words else 1
    entity_ok = bool(words) and any(sum(1 for w in words if w in t) >= need for t in texts)

    title_t = W._content_tokens(wedge.get("title", ""))
    dup_of = []
    for i, s in enumerate(siblings):
        if i == index:
            continue
        st = W._content_tokens(s.get("title", ""))
        if title_t and st and len(title_t & st) / min(len(title_t), len(st)) >= SIBLING_OVERLAP:
            dup_of.append(s.get("title", ""))

    checks = {
        "ids_exist": bool(ids) and all(e in registry for e in ids),
        "ids_in_card_evidence": bool(ids) and all(e in card_ids for e in ids),
        "cites_beyond_parent_space": bool(set(ids) - _space_ids(c, loader)),
        "entity_in_cited_text": entity_ok,
        "no_sibling_duplicate": not dup_of,
    }
    out = dict(checks)
    out["sibling_duplicate_of"] = dup_of
    out["checks_passed"] = sum(1 for v in checks.values() if v)
    out["checks_total"] = len(checks)
    return out


def validate_criteria(raw: Any, card: Any, wedge: Dict[str, Any], loader) -> (Dict[str, Dict[str, Any]], List[str]):
    """Validate Kimi's criteria. An invalid criterion is set to null with a note; nothing raises."""
    c = W._card_dict(card)
    registry = getattr(loader, "by_id", {}) or {}
    wedge_ids = [e for e in (wedge.get("evidence_ids") or []) if isinstance(e, str)]
    allowed_ids = set(wedge_ids) | set(c.get("evidence") or [])
    crit_in = raw.get("criteria") if isinstance(raw, dict) else None
    if not isinstance(crit_in, dict):
        crit_in = {}
    criteria, notes = {}, []
    for name in CRITERIA:
        item = crit_in.get(name)
        score = item.get("score") if isinstance(item, dict) else None
        reason = item.get("reason") if isinstance(item, dict) else None
        reason = reason.strip() if isinstance(reason, str) and reason.strip() else None
        problem = None
        if score is None:
            problem = None if isinstance(item, dict) else "missing"
        elif isinstance(score, bool) or not isinstance(score, int) or not 0 <= score <= 4:
            problem = "score is not an integer 0-4"
        elif reason is None:
            problem = "score given without a reason"
        else:
            cited = W.RECORD_ID_RE.findall(reason)
            bad = [i for i in cited if i not in registry]
            outside = [i for i in cited if i in registry and i not in allowed_ids]
            if bad:
                problem = "reason cites non-existent id: %s" % ", ".join(bad)
            elif outside:
                problem = "reason cites id outside wedge/card evidence: %s" % ", ".join(outside)
            else:
                texts = [_record_text(registry[i]) for i in set(wedge_ids) | set(cited) if i in registry]
                missing = W._nums_in(reason) - W._nums_in(" ".join(texts))
                if missing:
                    problem = "reason has number not in cited records: %s" % ", ".join(sorted(missing))
        if problem:
            notes.append("%s nulled: %s" % (name, problem))
            criteria[name] = {"score": None, "reason": None}
        else:
            criteria[name] = {"score": score, "reason": reason if score is not None else reason}
    return criteria, notes


def compute_score(criteria: Dict[str, Dict[str, Any]]) -> Optional[int]:
    """25 * weighted mean of KNOWN criteria (weights renormalised). Unknown is never 0."""
    known = {n: criteria[n]["score"] for n in CRITERIA
             if isinstance(criteria.get(n), dict) and criteria[n].get("score") is not None}
    if len(CRITERIA) - len(known) > MAX_UNKNOWN:
        return None
    wsum = sum(WEIGHTS[n] for n in known)
    if wsum <= 0:
        return None
    return int(round(25.0 * sum(WEIGHTS[n] * s for n, s in known.items()) / wsum))


def label_for(score: Optional[int]) -> str:
    if score is None:
        return "unscored"
    if score >= 75:
        return "high"
    if score >= 50:
        return "medium"
    return "low"


def _assemble(criteria, notes, checks, model) -> Dict[str, Any]:
    score = compute_score(criteria)
    label = label_for(score)
    review = []
    if label == "high" and (not checks["entity_in_cited_text"] or not checks["ids_exist"]
                            or not checks["ids_in_card_evidence"]):
        label = "medium"
        review.append("label capped at medium: entity not found in cited text or evidence ids missing")
    if label == "low":
        review.append("model-assessed validity is low")
    if label == "unscored":
        review.append("validity could not be scored (2+ criteria unknown/invalid or scoring failed)")
    return {
        "score": score,
        "label": label,
        "basis": "llm_assessed",
        "note": "Model-assessed by an independent LLM; not verified against the data beyond data_checks.",
        "scored_by": model_label(model),
        "criteria": criteria,
        "data_checks": checks,
        "needs_human_review": bool(review),
        "review_reasons": review,
        "notes": notes,
    }


def _unscored(checks, model, note) -> Dict[str, Any]:
    crit = {n: {"score": None, "reason": None} for n in CRITERIA}
    return _assemble(crit, [note], checks, model)


# --------------------------------------------------------------------------- entry points

def score_wedges(card: Any, wedges: List[Dict[str, Any]], loader, chat_fn: Optional[Callable] = None,
                 model: Optional[str] = None, sleep: Callable = time.sleep) -> List[Dict[str, Any]]:
    """Attach 'validity' to each (already validated) wedge. Same order. Never raises; never caches."""
    model = model or os.environ.get("FACTS_SCORE_MODEL", "").strip() or DEFAULT_SCORE_MODEL
    wedges = [w for w in (wedges or []) if isinstance(w, dict)]
    if chat_fn is None:
        chat_fn = W.call_gateway if W._get_client() is not None else None
    out = []
    for idx, orig in enumerate(wedges):
        w = dict(orig)
        try:
            checks = data_checks(card, w, wedges, loader, index=idx)
        except Exception:
            checks = {"ids_exist": False, "ids_in_card_evidence": False, "cites_beyond_parent_space": False,
                      "entity_in_cited_text": False, "no_sibling_duplicate": False,
                      "sibling_duplicate_of": [], "checks_passed": 0, "checks_total": 5}
        try:
            if chat_fn is None:
                w["validity"] = _unscored(checks, model, "scoring skipped: gateway unavailable")
            else:
                raw = _extract_json_object(W.ask_text(model, build_messages(card, w, wedges, loader, index=idx), chat_fn, sleep))
                if raw is None:
                    w["validity"] = _unscored(checks, model, "scoring failed: empty, truncated, error or non-JSON reply")
                else:
                    criteria, notes = validate_criteria(raw, card, w, loader)
                    w["validity"] = _assemble(criteria, notes, checks, model)
        except Exception as exc:
            w["validity"] = _unscored(checks, model, "scoring failed: %s" % type(exc).__name__)
        out.append(w)
    return out


def order_by_validity(wedges: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Score descending, unscored last, stable otherwise."""
    def key(item):
        idx, w = item
        s = (w.get("validity") or {}).get("score")
        return (s is None, -(s or 0), idx)
    return [w for _, w in sorted(enumerate(wedges), key=key)]


def scoring_report(wedges: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Per-wedge scoring failures/notes for wedge_validation_report.json."""
    out = []
    for w in wedges:
        v = w.get("validity") or {}
        if v.get("label") == "unscored" or v.get("notes"):
            out.append({"title": w.get("title"), "label": v.get("label"), "score": v.get("score"),
                        "notes": v.get("notes", [])})
    return out
